"""
Export the shared model spec to:
  models/<name>.gltf   - glTF 2.0 (flat-shaded, embedded buffer), opens in Blender/three.js/etc.
  src/models.js        - compact polygon data the game's renderer uses

Usage:  python3 tools/export_models.py
"""
import base64, json, math, os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "models"))
from tank_spec import MATERIALS, all_models  # noqa: E402


def triangulate(poly):
    return [(poly[0], poly[i], poly[i + 1]) for i in range(1, len(poly) - 1)]


def normal(a, b, c):
    u = [b[i] - a[i] for i in range(3)]
    v = [c[i] - a[i] for i in range(3)]
    n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]]
    l = math.sqrt(sum(x * x for x in n)) or 1.0
    return [x / l for x in n]


def export_gltf(name, parts, path):
    used = sorted({p.material for p in parts}, key=list(MATERIALS).index)
    mat_index = {m: i for i, m in enumerate(used)}
    buf = bytearray()
    accessors, views, meshes, nodes = [], [], [], []

    def add_view(data, target):
        while len(buf) % 4:
            buf.append(0)
        views.append({"buffer": 0, "byteOffset": len(buf), "byteLength": len(data), "target": target})
        buf.extend(data)
        return len(views) - 1

    part_node = {}
    for p in parts:
        pos, nor = [], []
        # vertices are stored relative to the node origin (the pivot for jointed parts)
        local = p.verts
        for poly in p.faces:
            for tri in triangulate(poly):
                a, b, c = (local[i] for i in tri)
                n = normal(a, b, c)
                for v in (a, b, c):
                    pos.append(v)
                    nor.append(n)
        pdata = b"".join(struct.pack("<3f", *v) for v in pos)
        ndata = b"".join(struct.pack("<3f", *v) for v in nor)
        pv, nv = add_view(pdata, 34962), add_view(ndata, 34962)
        accessors.append({"bufferView": pv, "componentType": 5126, "count": len(pos), "type": "VEC3",
                          "min": [min(v[i] for v in pos) for i in range(3)],
                          "max": [max(v[i] for v in pos) for i in range(3)]})
        accessors.append({"bufferView": nv, "componentType": 5126, "count": len(nor), "type": "VEC3"})
        meshes.append({"name": p.name, "primitives": [{
            "attributes": {"POSITION": len(accessors) - 2, "NORMAL": len(accessors) - 1},
            "material": mat_index[p.material]}]})
        node = {"name": p.name, "mesh": len(meshes) - 1}
        part_node[p.name] = len(nodes)
        nodes.append(node)

    # Jointed parts: the barrel's verts are authored relative to its pivot, so its node
    # gets the pivot as translation and is parented to the turret node.
    roots = []
    for p in parts:
        idx = part_node[p.name]
        if p.parent:
            nodes[idx]["translation"] = list(p.pivot)
            par = nodes[part_node[p.parent]]
            # turret node sits at origin, so translation stays in model space
            par.setdefault("children", []).append(idx)
        else:
            roots.append(idx)
    nodes.append({"name": name.capitalize(), "children": roots})

    gltf = {
        "asset": {"version": "2.0", "generator": "scorched-earth tank_spec exporter"},
        "scene": 0,
        "scenes": [{"name": name, "nodes": [len(nodes) - 1]}],
        "nodes": nodes,
        "meshes": meshes,
        "materials": [{"name": m, "pbrMetallicRoughness": {
            "baseColorFactor": list(MATERIALS[m][0]) + [1.0],
            "metallicFactor": MATERIALS[m][1], "roughnessFactor": MATERIALS[m][2]}} for m in used],
        "accessors": accessors,
        "bufferViews": views,
        "buffers": [{"byteLength": len(buf),
                     "uri": "data:application/octet-stream;base64," + base64.b64encode(bytes(buf)).decode()}],
    }
    with open(path, "w") as f:
        json.dump(gltf, f, separators=(",", ":"))
    return sum(a["count"] for a in accessors[::2]) // 3


def export_js(models, path):
    out = {}
    for name, parts in models.items():
        out[name] = [{
            "name": p.name, "mat": p.material,
            "pivot": list(p.pivot) if p.parent else None,
            "v": [c for v in p.verts for c in v],
            "f": p.faces,
        } for p in parts]
    mats = {k: [round(c * 255) for c in v[0]] for k, v in MATERIALS.items()}
    with open(path, "w") as f:
        f.write("// AUTO-GENERATED by tools/export_models.py from models/tank_spec.py - do not edit.\n")
        f.write("const MODEL_MATERIALS = " + json.dumps(mats, separators=(",", ":")) + ";\n")
        f.write("const MODELS = " + json.dumps(out, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    models = all_models()
    for name, parts in models.items():
        tris = export_gltf(name, parts, os.path.join(ROOT, "models", name + ".gltf"))
        print(f"models/{name}.gltf  {tris} triangles")
    export_js(models, os.path.join(ROOT, "src", "models.js"))
    print("src/models.js written")
